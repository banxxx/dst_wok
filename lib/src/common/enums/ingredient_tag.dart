/// 定义食材的九大属性标签
/// 根据饥荒游戏机制设计
enum IngredientTag {
  meat,       // 肉度
  fish,       // 鱼度
  egg,        // 蛋度
  veggie,     // 菜度
  fruit,      // 果度
  sweetener,  // 蜂蜜度
  dairy,      // 乳制品
  monster,    // 怪物度
  inedible,   // 不可食用度
  seed,       // 种子度
  fat,        // 油脂度
  decoration, // 装饰度
  magic,      // 魔法度
  frozen,     // 冰度
}